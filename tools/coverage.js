// Coverage report: how much question data each Premier League club has, and whether a Club Cup tie
// can be built from club questions alone. Run from the project root:  node tools/coverage.js
// Writes COVERAGE.md. Read-only: never changes data.js.
const fs = require("fs"), path = require("path");
const { load } = require("../tests/harness.js");
const g = load();
const rows = JSON.parse(g.run(`(() => {
  const TYPES11 = ["cell", "squad", "odd", "career", "mates", "top", "race", "xi", "hl", "champ", "season"];
  // "Premier League club" = any club with a Premier League squad on record (2010-11 onwards) or named in a Premier League table/line-up
  const now = CLUB.map((n, c) => c).filter(c => PLC.has(c) || [...Array(SQN).keys()].some(y => squadOf(c, y).filter(isPLp).length >= 15 && PLC.has(c)));
  const picker = new Set(BD.gridClubs);
  return JSON.stringify(now.map(c => {
    const name = CLUB[c], lists = listsOf(c).length, xi = BD.xi.filter(x => x[0] === name).length, xiAny = BD.xi.filter(x => x[0] === name || x[1] === name).length;
    const tabs = BD.tables.filter(t => t[3].some(r => r[0] === name)).length, releg = BD.tables.filter(t => t[4].includes(name)).length;
    const hl = BD.hl.filter(h => h[1] === c || h[2] === c).length, players = clubPl[c].length;
    let sq = 0; for (let y = 0; y < SQN; y++) if (squadOf(c, y).length >= 15) sq++;
    const careers = CAREERS.filter(i => hasClub(i, c)).length;
    // which of the 11 question types can be built for this club, per tier (sampled over 12 seeds)
    const ok = [0, 1, 2, 3].map(tier => TYPES11.filter(t => { let n = 0; for (let k = 0; k < 12; k++) if (makeScoped(t, rngOf(hash("cov" + c + t + tier + k)), tier, { club: c })) n++; return n >= 9; }));
    // how often a five-question cup tie needs padding (fewer than five distinct club types), over 40 seeds at tier 1
    let padded = 0, distinct = 0; for (let k = 0; k < 40; k++) { const m = makeCupMatch("cov-" + c + "-" + k, c, 1), ty = new Set(m.map(x => x.type)); distinct += ty.size; if (ty.size < 5) padded++; }
    const latest = (() => { for (let y = SQN - 1; y >= 0; y--) if (squadOf(c, y).length >= 15) return y; return -1; })();
    return { c, name, picker: picker.has(c), lists, xi, xiAny, tabs, releg, hl, players, sq, latest, careers, types: ok.map(a => a.length), missing0: TYPES11.filter(t => !ok[1].includes(t)), padded, distinct: +(distinct / 40).toFixed(2) };
  }));
})()`));
const SQ0 = 2010, lab = y => y < 0 ? "–" : (SQ0 + y) + "–" + String(SQ0 + y + 1).slice(2);
rows.sort((a, b) => (b.picker - a.picker) || a.types[1] - b.types[1] || (a.lists + a.xi + a.tabs + a.hl) - (b.lists + b.xi + b.tabs + b.hl));
const inPick = rows.filter(r => r.picker), out = rows.filter(r => !r.picker);
const line = r => `| ${r.name} | ${r.lists} | ${r.xi} | ${r.tabs} | ${r.hl} | ${r.players} | ${r.sq} | ${lab(r.latest)} | ${r.careers} | ${r.types.join(" / ")} | ${r.missing0.join(", ") || "none"} | ${r.padded}/40 |`;
const head = "| Club | Top tens | Line-ups | Final tables (top 4) | Transfers | Players | Squad seasons | Latest squad | Career paths | Cup types buildable (of 11) by tier 0/1/2/3 | Types that can't be built (tier 1) | Cup ties needing padding |\n|---|---|---|---|---|---|---|---|---|---|---|---|";
const thin = inPick.filter(r => r.lists + r.xi + r.tabs + r.hl < 12).map(r => r.name);
const md = `# Question data coverage by Premier League club

Generated by \`node tools/coverage.js\` on ${new Date().toLocaleDateString("en-GB")} from data.js as shipped. Regenerate after any data change.

**How to read it.** A Club Cup tie is five questions about one club, drawn from 11 question types. Six types only need player records
(The Grid, Squad Sheet, Odd One Out, Career Path, The Link, plus Missing XI when line-ups exist); the other five need club-specific
lists, line-ups, final tables or transfer records. "Cup types buildable" is how many of the 11 can be made for the club at each
difficulty tier. "Needing padding" is how many of 40 sample ties ended up with fewer than five different question types (the tie
still works; it repeats The Grid).

## Clubs you can pick in the game (${inPick.length})
${head}
${inPick.map(line).join("\n")}

## Premier League clubs in the data but not in the club picker (${out.length})
${head}
${out.map(line).join("\n")}

## Thinnest pickable clubs (fewer than 12 club-specific records across top tens, line-ups, tables and transfers)
${thin.length ? thin.join(", ") : "None."}
`;
fs.writeFileSync(path.join(__dirname, "..", "COVERAGE.md"), md);
