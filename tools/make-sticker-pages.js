// Builds sticker-pages.js: the frozen sticker album pages (18 slots per club).
// Pages are FROZEN on purpose: once players have stickers, a page must never reshuffle, whatever happens to data.js later.
//   node tools/make-sticker-pages.js            first build (refuses to overwrite an existing file)
//   node tools/make-sticker-pages.js --add      keep every existing page exactly as it is, only add pages for new clubs
//   node tools/make-sticker-pages.js --report   print the coverage report without writing anything
const fs = require("fs"), path = require("path");
const { load } = require("../tests/harness.js");
const OUT = path.join(__dirname, "..", "sticker-pages.js"), exists = fs.existsSync(OUT), add = process.argv.includes("--add"), reportOnly = process.argv.includes("--report");
if (exists && !add && !reportOnly) { console.error("sticker-pages.js already exists and is frozen. Use --add to add new clubs, or --report to just look."); process.exit(1); }
const g = load({ skip: exists && !add && !reportOnly ? [] : (add || reportOnly) ? [] : ["sticker-pages.js"] });
const res = JSON.parse(g.run(`(() => {
  const R = STICKER_RULES, out = { pages: [], thin: [], stats: {} };
  const noNat = PL.filter(p => p[1] < 0).length, noBirth = PL.filter(p => !(p[3] > 0)).length, oneClub = PL.filter((p, i) => clubsOf(i).length < 2).length;
  out.stats = { players: PL.length, noNat, noBirth, oneClub, eligible: PL.filter((p, i) => stkEligible(i)).length };
  CLUBS_PICK.forEach(c => {
    const all = clubPl[c], elig = all.filter(i => stkEligible(i)), stay = elig.filter(i => !stkShortStay(i, c));
    const ranked = stay.slice().sort((a, b) => stkRank(b, c) - stkRank(a, c) || a - b).slice(0, R.pageSize);
    const row = { club: CLUB[c], players: all.length, eligible: elig.length, afterLoans: stay.length };
    if (ranked.length < R.pageSize) { out.thin.push(row); return; }
    out.pages.push({ c: CLUB[c], s: ranked.map(pkey), names: ranked.map(i => PL[i][0] + " (" + fame(i) + ", " + stkTenure(i, c) + "y)"), row });
  });
  return JSON.stringify(out);
})()`));
let pages = res.pages.map(p => ({ c: p.c, s: p.s }));
if (add && exists) {
  const old = JSON.parse(fs.readFileSync(OUT, "utf8").replace(/^[\s\S]*?window\.BOFFIN_PAGES = /, "").replace(/;\s*$/, ""));
  const have = new Set(old.map(p => p.c)), fresh = pages.filter(p => !have.has(p.c));
  pages = old.concat(fresh); console.log("kept", old.length, "pages, added", fresh.length);
}
const st = res.stats;
const report = `Sticker pages: ${res.pages.length} clubs x 18 = ${res.pages.length * 18} stickers.
Players in the book: ${st.players}. Can be offered (nationality, birth year and a club with a year all on file): ${st.eligible}.
Excluded for missing clue data: ${st.players - st.eligible} (no nationality: ${st.noNat}; no birth year: ${st.noBirth}; some overlap).
Clubs in the picker without a page (fewer than 18 eligible players after dropping stays of a year or less): ${res.thin.length ? res.thin.map(r => r.club + " (" + r.afterLoans + ")").join(", ") : "none"}.

Page by page (slots 1-3 Gold Icon, 4-8 Foil, 9-18 Paper; number in brackets is the fame score used for ranking):
${res.pages.map(p => p.c + ": " + p.names.join(", ")).join("\n")}
`;
fs.mkdirSync(path.join(__dirname, "..", "tests", "out"), { recursive: true });
fs.writeFileSync(path.join(__dirname, "..", "STICKER-PAGES.md"), "# Sticker pages (frozen)\n\nGenerated by `node tools/make-sticker-pages.js` on " + new Date().toLocaleDateString("en-GB") + ". Do not regenerate: use `--add` for new clubs only.\n\n```\n" + report + "```\n");
console.log(report.split("\n").slice(0, 5).join("\n"));
if (!reportOnly) {
  fs.writeFileSync(OUT, "// FROZEN sticker album pages: 18 players per club, by name|birth-year key. Made by tools/make-sticker-pages.js.\n// Never reorder or regenerate (players' albums point at these slots). To add clubs: node tools/make-sticker-pages.js --add\nwindow.BOFFIN_PAGES = " + JSON.stringify(pages).replace(/\},\{/g, "},\n{") + ";\n");
  console.log("wrote sticker-pages.js", (fs.statSync(OUT).size / 1024).toFixed(1) + " KB");
}
